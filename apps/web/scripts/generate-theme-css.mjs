/**
 * Generates app/theme.generated.css from utilities/palette.mjs.
 *
 * palette.mjs is the single source of truth for colors: OG image generation
 * (@vercel/og) needs TS/JS literals, while the CSS layer needs custom
 * properties — this script keeps the two in sync. The output is committed so
 * `next dev` works without a generation step; it is regenerated on every
 * `pnpm build` (same pattern as generate-og-assets.mjs).
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  genreGradients,
  scales,
  semantic,
  themeGradient,
} from "../utilities/palette.mjs";

const outFile = join(
  dirname(fileURLToPath(import.meta.url)),
  "../app/theme.generated.css",
);

const lines = [];

lines.push(`/* AUTO-GENERATED by scripts/generate-theme-css.mjs — do not edit.
   Source of truth: utilities/palette.mjs. Regenerate with:
   pnpm --filter @midhah/web generate:theme-css */`);
lines.push("");

/* Primitive scales as plain custom properties (deliberately NOT @theme
   tokens: components must use the semantic tokens below, and plain vars
   cannot collide with Tailwind's stock teal/cyan utility scales). */
lines.push(":root {");
for (const [name, steps] of Object.entries(scales)) {
  for (const [step, value] of Object.entries(steps)) {
    lines.push(`  --${name}-${step}: ${value};`);
  }
}
lines.push("");
lines.push(`  --gradient-hero-base: ${themeGradient.base};`);
lines.push(`  --gradient-hero: ${themeGradient.image};`);
for (const [genre, gradient] of Object.entries(genreGradients)) {
  lines.push(`  --gradient-genre-${genre}: ${gradient};`);
}
lines.push("");
for (const [token, value] of Object.entries(semantic.light)) {
  lines.push(`  --sem-${token}: ${value};`);
}
lines.push("}");
lines.push("");

lines.push(`[data-theme="dark"] {`);
for (const [token, value] of Object.entries(semantic.dark)) {
  lines.push(`  --sem-${token}: ${value};`);
}
lines.push("}");
lines.push("");

/* Semantic tokens exposed as Tailwind utilities (bg-surface, text-ink, …).
   Declared with `inline` so utilities compile to var() references that flip
   with [data-theme]. */
lines.push("@theme inline {");
for (const token of Object.keys(semantic.light)) {
  lines.push(`  --color-${token}: var(--sem-${token});`);
}
lines.push("}");
lines.push("");

/* Genre gradient utilities (replacement for style={{ background }}). */
for (const genre of Object.keys(genreGradients)) {
  lines.push(`@utility bg-genre-${genre} {`);
  lines.push(`  background-image: var(--gradient-genre-${genre});`);
  lines.push("}");
  lines.push("");
}

writeFileSync(outFile, lines.join("\n"));
console.log(`✓ theme.generated.css written (${lines.length} lines)`);
