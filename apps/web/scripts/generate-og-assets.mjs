// Inlines the OG renderer's images as base64 data URIs.
//
// Satori runs on the edge, where there is no filesystem, and Turbopack resolves
// `new URL("./x.png", import.meta.url)` to a root-relative path that server-side
// `fetch` cannot parse. Baking the bytes into a module sidesteps both problems and
// keeps the renderer free of any dependency on a deployed origin.
//
// Wired into `pnpm build`, so the output cannot drift from the source images.
// Run manually after editing them: `pnpm --filter @midhah/web generate:og-assets`

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const currentDir = path.dirname(fileURLToPath(import.meta.url));

const sources = [
  {
    name: "OG_PATTERN",
    file: "pattern.svg",
    mime: "image/svg+xml",
    path: path.join(currentDir, "../public/images/pattern.svg"),
  },
  {
    name: "OG_MARK",
    file: "mark.svg",
    mime: "image/svg+xml",
    path: path.join(
      currentDir,
      "../app/[genre]/[slug]/_components/og/mark.svg",
    ),
  },
];

const parts = await Promise.all(
  sources.map(async ({ name, mime, path: filePath }) => {
    const base64 = (await readFile(filePath)).toString("base64");
    return `export const ${name} =\n  "data:${mime};base64,${base64}";\n`;
  }),
);

await writeFile(
  path.join(
    currentDir,
    "../app/[genre]/[slug]/_components/og",
    "assets.generated.ts",
  ),
  `// GENERATED by scripts/generate-og-assets.mjs — do not edit.\n` +
    `// Edit the source images in this folder and rebuild instead.\n\n` +
    parts.join("\n"),
);

console.log(`generated assets.generated.ts from ${sources.length} images`);
