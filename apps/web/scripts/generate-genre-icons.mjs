// Generates the inline genre icon components from public/images/genres/*.svg.
//
// The artwork is needed in two forms: inline SVG on the homepage cards (so the
// strokes inherit `currentColor` and can be themed), and a plain URL in LyricCard,
// which renders up to hundreds of rows and must not repeat the path data per node.
// Generating one from the other keeps a single source of truth.
//
// Wired into `pnpm build`. Run manually after re-tracing the artwork:
// `pnpm --filter @midhah/web generate:genre-icons`

import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const currentDir = path.dirname(fileURLToPath(import.meta.url));
const svgDir = path.join(currentDir, "../assets/genres");
const outDir = path.join(currentDir, "../components/icons");

// genre slug -> component name
const components = {
  hamd: "BaitUllah",
  naat: "RozaERasool",
  manqbat: "RozaEImamHussain",
  "durood-o-salam": "GoshaEDurood",
};

const files = (await readdir(svgDir)).filter((f) => f.endsWith(".svg"));

for (const file of files) {
  const slug = path.basename(file, ".svg");
  const name = components[slug];
  if (!name) throw new Error(`No component name mapped for genre "${slug}"`);

  const svg = await readFile(path.join(svgDir, file), "utf8");
  const d = svg.match(/\sd="([^"]+)"/)?.[1];
  if (!d) throw new Error(`No path data found in ${file}`);

  // Only the `d` attribute is carried across, so anything that positions the artwork
  // from outside the path would be silently dropped here — leaving the inline card
  // icons misaligned while the URL-referenced ones stayed correct.
  if (/transform=|<g[\s>]/.test(svg)) {
    throw new Error(
      `${file} has a transform or <g> wrapper; bake it into the path data first ` +
        `(see scripts/normalize-genre-icons.mjs)`,
    );
  }

  await writeFile(
    path.join(outDir, `${name}.tsx`),
    `// GENERATED by scripts/generate-genre-icons.mjs from public/images/genres/${file}
// Do not edit — change the SVG and rebuild instead.
import type { SVGProps } from "react";

const ${name} = (props: SVGProps<SVGSVGElement>) => (
  <svg viewBox="0 0 1000 1000" fill="currentColor" {...props}>
    <path fillRule="evenodd" d="${d}" />
  </svg>
);

export default ${name};
`,
  );
}

console.log(`generated ${files.length} genre icon components`);
